#!/usr/bin/env python3
"""replica/design/tokens.json -> CSS variables + Tailwind v4 @theme, written to src/styles/tokens.css and replica/design/tokens.css.
Adapted from Quietkey's generator. Rerun after token changes."""
import json, pathlib

app = pathlib.Path(__file__).resolve().parent.parent
src = app.parent / "replica" / "design" / "tokens.json"
t = json.loads(src.read_text())
c = t["color"]
light = {k: v for k, v in c.items() if isinstance(v, str)}
dark, bar = c["dark"], c["bar"]
assert set(light) == set(dark), "light and dark must define the same roles: %s" % (set(light) ^ set(dark))

def block(d, prefix="", indent="  "):
    return "\n".join("%s--c-%s%s: %s;" % (indent, prefix, k, v) for k, v in d.items())

# Tailwind class names: text-fg, text-muted, text-ai, border-input (avoids text-text and the --text-* font-size namespace)
ALIAS = {"text": "fg", "text-muted": "muted", "text-ai": "ai", "border-input": "input"}

out = ["/* Generated by app/scripts/gen_tokens.py from replica/design/tokens.json. Do not edit by hand. */", "", ":root {",
       block(light), block(bar, "bar-")]
out += ["  --motion-%s: %s;" % (k, v) for k, v in t["motion"].items()]
out += ["  --%s: %spx;" % (k, v) for k, v in t["layout"].items()]
out += ["  color-scheme: light;", "}", "",
        "/* theme=system follows the OS; theme=light|dark is set on <html data-theme> */",
        "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", block(dark, indent="    "),
        "    color-scheme: dark;", "  }", "}", ":root[data-theme=\"dark\"] {", block(dark), "  color-scheme: dark;", "}", "",
        "/* Tailwind v4: bg-surface, text-muted, text-ai, border-input, rounded-bubble, shadow-pop, text-note ... */", "@theme inline {"]
out += ["  --color-%s: var(--c-%s);" % (ALIAS.get(k, k), k) for k in light]
out += ["  --color-bar-%s: var(--c-bar-%s);" % (k, k) for k in bar]
out += ["  --font-sans: %s;" % t["font"]["sans"], "  --font-mono: %s;" % t["font"]["mono"]]
out += ["  --radius-%s: %spx;" % (k, v) for k, v in t["radius"].items()]
out += ["  --shadow-%s: %s;" % (k, v) for k, v in t["shadow"].items()]
for k, v in t["type"].items():
    out += ["  --text-%s: %spx;" % (k, v["size"]), "  --text-%s--line-height: %spx;" % (k, v["line"]),
            "  --text-%s--font-weight: %s;" % (k, v["weight"])]
out += ["  --spacing: 4px;", "}", ""]
css = "\n".join(out)
for dest in (app / "src" / "styles" / "tokens.css", src.parent / "tokens.css"):
    dest.write_text(css)
    print("wrote", dest)
